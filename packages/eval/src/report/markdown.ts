/**
 * Emits `docs/architecture/07a_AI_Provider_Evaluation.md` — the deliverable
 * doc 07 §6 names as the output of this harness.
 *
 * The report is written to be read by someone deciding, not someone debugging:
 * the scorecard first, the caveats immediately after, the raw per-case data
 * last. Two things it deliberately does *not* do:
 *
 *   - It never picks a winner. A harness that prints "recommended: X" invites
 *     the reader to skip the caveats, and the caveats are where the human
 *     dimensions and the unreviewed cases live.
 *   - It never hides what was not measured. An unscored dimension prints as
 *     "not measured", never as a zero or a blank that reads like one.
 */

import type { RunReport, CandidateSummary } from '../types.js';
import type { MonthlyProjection } from '../metrics/cost.js';

export interface ReportContext {
  report: RunReport;
  /** Per-candidate monthly projection, keyed by candidate id. */
  projections?: Record<string, MonthlyProjection>;
  /** True once a native speaker has filled in the blind review sheet. */
  humanReviewComplete: boolean;
}

export function renderEvaluationReport(context: ReportContext): string {
  const { report, projections, humanReviewComplete } = context;

  const sections = [
    header(report),
    decisionStatus(report, humanReviewComplete),
    scorecard(report),
    latencySection(report),
    costSection(report, projections),
    caveats(report, humanReviewComplete),
    perCaseAppendix(report),
  ];

  return sections.join('\n\n');
}

function header(report: RunReport): string {
  return [
    '# AI Tutor Bangladesh — AI Provider Evaluation',
    '',
    '> Generated by `packages/eval`. Do not hand-edit — re-run the harness.',
    '',
    `**Suite:** ${report.suite} · **Run:** \`${report.runId}\` · ` +
      `**Dataset:** v${report.datasetVersion}`,
    `**Started:** ${report.startedAt} · **Finished:** ${report.finishedAt}`,
    '',
    'This document exists to close D-09 (chat LLM), D-10 (vision/OCR) and D-11',
    '(embedding model) from doc 07 §2.2. Doc 07 is explicit that the choice is made',
    'by measured Bangla quality, not reputation.',
  ].join('\n');
}

function decisionStatus(report: RunReport, humanReviewComplete: boolean): string {
  const blockers: string[] = [];

  if (!humanReviewComplete) {
    blockers.push(
      'Native-speaker Bangla fluency review (§6 dimension 2) has not been completed. ' +
        "This is the product's core promise and cannot be automated — run " +
        '`pnpm eval:sheet` and have a Bangla-speaking teacher fill it in.',
    );
  }

  if (report.unreviewedCaseIds.length > 0) {
    blockers.push(
      `${report.unreviewedCaseIds.length} of ${report.results.length / Math.max(1, report.candidates.length)} ` +
        'test cases have not been signed off by a subject-matter expert, so ' +
        '"factual correctness" is measured against unverified reference answers ' +
        '(doc 07 §13 item 5).',
    );
  }

  if (report.candidates.length < 2) {
    blockers.push('Fewer than two candidates ran. A comparison of one is not a decision.');
  }

  if (blockers.length === 0) {
    return [
      '## Decision status',
      '',
      '**Ready to decide.** All dimensions measured, all reference answers reviewed,',
      'and more than one candidate ran.',
    ].join('\n');
  }

  return [
    '## Decision status',
    '',
    '**Not ready to decide.** Outstanding:',
    '',
    ...blockers.map((blocker) => `- ${blocker}`),
  ].join('\n');
}

function scorecard(report: RunReport): string {
  if (report.candidates.length === 0) {
    return '## Scorecard\n\nNo candidates ran.';
  }

  const dimensions = collectDimensions(report.candidates);

  const head = ['| Candidate | ' + dimensions.join(' | ') + ' | Errors |'];
  const rule = ['|---|' + dimensions.map(() => '---|').join('') + '---|'];

  const rows = report.candidates.map((candidate) => {
    const cells = dimensions.map((dimension) => {
      const value = candidate.dimensionMeans[dimension];
      return value === undefined ? '_not measured_' : formatScore(value);
    });
    return `| \`${candidate.candidateId}\` | ${cells.join(' | ')} | ${candidate.errorCount} |`;
  });

  return [
    '## Scorecard',
    '',
    'Scores are 0–1. Human-rated dimensions are rescaled from the 1–5 review sheet.',
    '',
    ...head,
    ...rule,
    ...rows,
  ].join('\n');
}

function latencySection(report: RunReport): string {
  if (report.candidates.length === 0) return '';

  const rows = report.candidates.map((candidate) => {
    const { latency } = candidate;
    const meetsBudget = latency.p95TtftMs > 0 && latency.p95TtftMs < 2500;
    return (
      `| \`${candidate.candidateId}\` | ${latency.p50TtftMs} ms | ${latency.p95TtftMs} ms | ` +
      `${latency.p50Ms} ms | ${latency.p95Ms} ms | ${meetsBudget ? 'yes' : 'no'} |`
    );
  });

  return [
    '## Latency',
    '',
    'Doc 07 §5.4 budgets AI first token at p95 < 2.5 s. Measured from a developer',
    'machine — re-measure from the chosen hosting region (D-15) before treating',
    'the budget column as settled.',
    '',
    '| Candidate | TTFT p50 | TTFT p95 | Total p50 | Total p95 | Within 2.5 s budget |',
    '|---|---|---|---|---|---|',
    ...rows,
  ].join('\n');
}

function costSection(report: RunReport, projections?: Record<string, MonthlyProjection>): string {
  if (report.candidates.length === 0) return '';

  const rows = report.candidates.map((candidate) => {
    const projection = projections?.[candidate.candidateId];
    const monthly = projection ? `৳${projection.monthlyCostBdt.toFixed(0)}` : '_not projected_';
    const share = projection ? `${(projection.shareOfPrice * 100).toFixed(0)}%` : '—';
    const verdict = projection ? (projection.withinBudget ? 'yes' : '**no**') : '—';

    return (
      `| \`${candidate.candidateId}\` | $${candidate.cost.perQuestionUsd.toFixed(5)} | ` +
      `${monthly} | ${share} | ${verdict} |`
    );
  });

  return [
    '## Cost',
    '',
    'Measured from provider-reported token usage against the prices in',
    '`packages/eval/pricing.json`. Doc 07 R-06 triggers action above 40% of the',
    '৳199 premium price.',
    '',
    '| Candidate | Per question | Projected / user / month | Share of ৳199 | Within budget |',
    '|---|---|---|---|---|',
    ...rows,
  ].join('\n');
}

function caveats(report: RunReport, humanReviewComplete: boolean): string {
  const items = [
    'Latency was measured from a developer machine, not from the production' +
      ' hosting region. D-15 changes these numbers.',
    'Cost per question is measured on this test set, whose questions are shorter' +
      ' than a real tutoring exchange with retrieved curriculum context attached.' +
      ' Treat it as a floor.',
  ];

  if (!humanReviewComplete) {
    items.push(
      'Bangla fluency is **not** in the scorecard above. The automated script check' +
        ' only verifies the answer is in Bangla, not that it reads naturally —' +
        ' exactly the distinction doc 07 R-04 is about.',
    );
  }

  if (report.unreviewedCaseIds.length > 0) {
    items.push(
      `Unreviewed cases: ${report.unreviewedCaseIds.map((id) => `\`${id}\``).join(', ')}.`,
    );
  }

  return ['## Caveats', '', ...items.map((item) => `- ${item}`)].join('\n');
}

function perCaseAppendix(report: RunReport): string {
  const failures = report.results.filter((result) => result.error);

  const lines = [
    '## Appendix — per-case results',
    '',
    `${report.results.length} results across ${report.candidates.length} candidates.`,
    'Full JSON in `packages/eval/results/`.',
  ];

  if (failures.length > 0) {
    lines.push(
      '',
      '### Failures',
      '',
      '| Candidate | Case | Language | Error |',
      '|---|---|---|---|',
      ...failures.map(
        (failure) =>
          `| \`${failure.candidateId}\` | ${failure.caseId} | ${failure.language} | ${failure.error} |`,
      ),
    );
  }

  return lines.join('\n');
}

function collectDimensions(candidates: CandidateSummary[]): string[] {
  const seen = new Set<string>();
  for (const candidate of candidates) {
    for (const dimension of Object.keys(candidate.dimensionMeans)) seen.add(dimension);
  }
  return [...seen].sort();
}

function formatScore(value: number): string {
  return value.toFixed(2);
}
